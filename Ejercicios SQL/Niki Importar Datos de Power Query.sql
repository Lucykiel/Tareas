CREATE TABLE IF NOT EXISTS ventas(
 año INT NOT NULL,
 mes INT NOT NULL,
 id INT NOT NULL,
 producto VARCHAR(100) NOT NULL,
 provincia VARCHAR(20) NOT NULL,
 ventas DECIMAL(10,2) NOT NULL
);

